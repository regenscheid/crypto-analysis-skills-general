#!/usr/bin/env python3
"""Generate each domain router's family table from config/skill-registry.json.

Each router gets `references/skill-family.md`, listing every specialist skill of
its domain with what it is for (the first sentence of its description), and a
short generated section in its SKILL.md that points at the table and tells the
similarly named symmetric and public-key skills apart. Run with --check to fail
when a generated file differs from what the registry gives.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

from audit_skills import parse_frontmatter

ROOT = Path(__file__).resolve().parents[1]
ROUTERS = {
    "symmetric": "symmetric-cryptanalysis-orchestrator",
    "public-key": "public-key-cryptanalysis-orchestrator",
    "formal": "formal-methods-router",
}
TITLES = {
    "symmetric": "Symmetric cryptanalysis",
    "public-key": "Public-key cryptanalysis",
    "formal": "Formal methods",
}
START = "<!-- family-table:start (generated by tools/family_tables.py; do not edit) -->"
END = "<!-- family-table:end -->"
STOP_WORDS = {"and", "analysis", "public", "key", "symmetric", "attack"}


def registry(root: Path) -> list[dict]:
    return json.loads((root / "config/skill-registry.json").read_text(encoding="utf-8"))["skills"]


def first_sentence(text: str, limit: int = 110) -> str:
    """The description's first sentence, cut at a word to keep the table small."""
    match = re.match(r"(.+?[.!?])(?:\s|$)", text)
    sentence = (match.group(1) if match else text).strip()
    if len(sentence) <= limit:
        return sentence
    return sentence[:limit].rsplit(" ", 1)[0].rstrip(",;:") + " …"


def similar_pairs(skills: list[dict]) -> list[tuple[str, str]]:
    """Unprefixed symmetric skills whose names resemble a public-key skill's."""
    symmetric = [s["skill_id"] for s in skills if s["domain"] == "symmetric"]
    public_key = [s["skill_id"] for s in skills if s["domain"] == "public-key"]
    pairs = []
    for name in symmetric:
        if name.startswith("symmetric-"):
            continue
        words = set(name.split("-")) - STOP_WORDS
        for other in public_key:
            if len(words & (set(other.split("-")) - STOP_WORDS)) >= 2:
                pairs.append((name, other))
    return sorted(pairs)


def family_table(root: Path, domain: str, skills: list[dict]) -> str:
    rows = []
    for skill in sorted(s["skill_id"] for s in skills if s["domain"] == domain):
        if skill == ROUTERS[domain]:
            continue
        description = parse_frontmatter(root / "skills" / skill / "SKILL.md")["description"]
        rows.append(f"| `{skill}` | {first_sentence(description).replace('|', '/')} |")
    return (f"# {TITLES[domain]}: specialist skills\n\n"
            f"Generated from `config/skill-registry.json` by `tools/family_tables.py`;\n"
            f"do not edit by hand. {len(rows)} skills. Read a skill before claiming to\n"
            f"use its procedure; a skill not installed is unavailable, not inapplicable.\n\n"
            "| Skill | For |\n|---|---|\n" + "\n".join(rows) + "\n")


def router_section(domain: str, pairs: list[tuple[str, str]]) -> str:
    lines = [START, "## Specialist skills", "",
             f"[The family table](references/skill-family.md) lists every {TITLES[domain].lower()}",
             "skill in this pack with what it is for. Route to the ones the target and",
             "claim need."]
    if domain in {"symmetric", "public-key"} and pairs:
        lines += ["", "Similar names, different domains: the unprefixed name is the symmetric skill.", ""]
        lines += [f"- `{sym}` (symmetric) / `{pk}` (public-key)" for sym, pk in pairs]
    lines.append(END)
    return "\n".join(lines) + "\n"


def with_section(text: str, section: str) -> str:
    if START in text:
        before, rest = text.split(START, 1)
        after = rest.split(END, 1)[1].lstrip("\n")
        return before + section + ("\n" + after if after else "")
    return text.rstrip("\n") + "\n\n" + section


def outputs(root: Path) -> dict[Path, str]:
    skills = registry(root)
    pairs = similar_pairs(skills)
    result = {}
    for domain, router in ROUTERS.items():
        directory = root / "skills" / router
        result[directory / "references" / "skill-family.md"] = family_table(root, domain, skills)
        skill_md = directory / "SKILL.md"
        result[skill_md] = with_section(skill_md.read_text(encoding="utf-8"), router_section(domain, pairs))
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if a generated file is stale")
    args = parser.parse_args()
    stale = []
    for path, text in outputs(ROOT).items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    for path in stale:
        print(f"STALE: {path}; run tools/family_tables.py", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
